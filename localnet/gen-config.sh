#!/usr/bin/env bash
# Writes localnet/config.yaml for the running localnet. Validator keys are
# generated fresh on every `make localnet-up`, so the consensus addresses are
# read from each node's /status rather than committed.
set -euo pipefail
cd "$(dirname "$0")"

# name role rpc-port
NODES="sentry sentry 26657
val0 validator 26757
val1 validator 26857
val2 validator 26957
val3 validator 27057"

wait_for() {
  for _ in $(seq 1 90); do
    h=$(curl -fsS "http://127.0.0.1:$1/status" 2>/dev/null | jq -r '.result.sync_info.latest_block_height' 2>/dev/null || true)
    if [[ -n "$h" && "$h" != "null" && "$h" -ge 3 ]]; then return 0; fi
    sleep 2
  done
  echo "node on port $1 did not start producing blocks" >&2
  return 1
}

{
  echo "# Generated by localnet/gen-config.sh for the running localnet. Do not edit."
  echo "cosmos:"
  echo "  rest: http://127.0.0.1:1317   # the sentry's REST API"
  echo "nodes:"
  while read -r name role rpc; do
    wait_for "$rpc"
    echo "  - name: $name"
    echo "    role: $role"
    echo "    rpc: http://127.0.0.1:$rpc"
    if [[ "$role" == validator ]]; then
      addr=$(curl -fsS "http://127.0.0.1:$rpc/status" | jq -r .result.validator_info.address)
      echo "    validator_address: $addr"
    fi
  done <<< "$NODES"
} > config.yaml.tmp
mv config.yaml.tmp config.yaml
echo "wrote localnet/config.yaml"
